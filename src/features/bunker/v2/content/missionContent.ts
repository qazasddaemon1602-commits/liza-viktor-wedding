export function normalizeBunkerMissionKey(value: string | null | undefined): BunkerMissionKey | undefined {
  const runtimeId = value?.trim().toUpperCase();
  if (!runtimeId) return undefined;

  if (/^FINAL(?:[_-]?30)?$/.test(runtimeId)) return 'FINAL';

  const mission = runtimeId.match(/^(?:M|MISSION[_-]?)(0?[1-6])$/);
  if (!mission) return undefined;

  return `M${mission[1].padStart(2, '0')}` as BunkerMissionKey;
}

export function getBunkerMissionContent(value: string | null | undefined): BunkerMissionContent | undefined {
  const key = normalizeBunkerMissionKey(value);
  return key ? CONTENT[key] : undefined;
}
