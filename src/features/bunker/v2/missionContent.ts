/**
 * Контентный слой Бункера V2.
 *
 * Единственный источник сюжетных текстов для игрока (мобильный брифинг) и для
 * ведущего (сценарий в админке). Слой чисто декларативный: он НЕ содержит
 * игровой механики, не обращается к RPC/realtime и не влияет на состояние.
 *
 * Масштабирование: добавляем запись в BUNKER_MISSION_CONTENT для M02–M06 и
 * финала, ничего больше менять не нужно.
 */

export type BunkerMissionContentKey =
  | 'M01'
  | 'M02'
  | 'M03'
  | 'M04'
  | 'M05'
  | 'M06'
  | 'FINAL';

export type BunkerMissionItemContent = {
  /** Ключ предмета/материала — совпадает с игровыми данными, если он там есть. */
  key: string;
  label: string;
  /** Зачем предмет нужен именно в этом задании. */
  purpose: string;
};

export type BunkerMissionHostScript = {
  /** Что ведущий говорит вслух перед началом задания. */
  say: readonly string[];
  /** Подсказки, если вагоны застряли. От мягкой к прямой. */
  hints: readonly string[];
  /** Что нажать в пульте после завершения. */
  afterCompletion: string;
};

export type BunkerMissionContent = {
  key: BunkerMissionContentKey;
  code: string;
  title: string;
  /** Краткая история: что происходит в сюжете. */
  story: string;
  /** Цель игрока одной фразой. */
  goal: string;
  /** Пошаговые действия игрока. */
  steps: readonly string[];
  /** Предметы/материалы и зачем они нужны. */
  items: readonly BunkerMissionItemContent[];
  /** Последствия решения для вагона и финала. */
  consequences: readonly string[];
  host: BunkerMissionHostScript;
};

