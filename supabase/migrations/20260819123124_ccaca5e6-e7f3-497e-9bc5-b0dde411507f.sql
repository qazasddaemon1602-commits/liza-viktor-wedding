      completed_at = null,
      completed_by_guest_id = null,
      updated_at = now()
  where event_id = p_event_id
    and run_nonce = v_state.run_nonce
    and carriage_id = p_carriage_id
    and stage = p_stage;

  return public.owner_get_bunker_quest(p_event_id);
end;
$$;

create or replace function public.owner_force_complete_bunker_team_stage(
  p_event_id uuid,
  p_carriage_id uuid,
  p_stage text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_state public.bunker_state%rowtype;
begin
  perform public._require_bunker_owner(p_event_id);

  if p_stage not in ('mission_a', 'mission_b') then
    raise exception 'invalid bunker mission stage' using errcode = '22023';
  end if;

  select b.* into v_state from public.bunker_state b where b.event_id = p_event_id;
  if v_state.run_nonce is null then
    raise exception 'bunker quest not initialized' using errcode = '55000';
  end if;

  update public.bunker_team_progress
  set completed_at = coalesce(completed_at, clock_timestamp()),
      updated_at = now()
  where event_id = p_event_id
    and run_nonce = v_state.run_nonce
    and carriage_id = p_carriage_id
    and stage = p_stage;

  return public.owner_get_bunker_quest(p_event_id);
end;
$$;

create or replace function public.owner_unlock_bunker(p_event_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public._require_bunker_owner(p_event_id);

  update public.bunker_state
  set unlocked_at = coalesce(unlocked_at, clock_timestamp()),
      updated_at = now()
  where event_id = p_event_id and status = 'active';

  if not found then
    raise exception 'bunker is not active' using errcode = '55000';
  end if;

  insert into public.owner_action_log(event_id, owner_user_id, action, payload)
  values (p_event_id, auth.uid(), 'bunker_manual_unlock', '{}'::jsonb);

  return public.owner_get_bunker_quest(p_event_id);
end;
$$;

