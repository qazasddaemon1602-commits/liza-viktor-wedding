create or replace function public._ensure_bunker_team_progress(
  p_event_id uuid,
  p_run_nonce uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.bunker_team_progress(
    event_id, run_nonce, carriage_id, stage, mission_template_id, reward_fragment
  )
  select
    p_event_id,
    p_run_nonce,
    c.id,
    t.stage,
    t.id,
    case
      when t.stage = 'mission_b' then lpad((10 + floor(random() * 90)::integer)::text, 2, '0')
      else null
    end
  from public.carriages c
  join public.bunker_mission_templates t on t.carriage_number = c.number
  where c.event_id = p_event_id and c.enabled
  on conflict (run_nonce, carriage_id, stage) do nothing;
end;
$$;

create or replace function public.owner_start_bunker(
  p_event_id uuid,
  p_duration_seconds integer default 1800
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_started_at timestamptz := clock_timestamp();
  v_run_nonce uuid := gen_random_uuid();
begin
  perform public._require_bunker_owner(p_event_id);

  if p_duration_seconds is null or p_duration_seconds not between 60 and 7200 then
    raise exception 'bunker duration must be between 60 and 7200 seconds' using errcode = '22023';
  end if;

  insert into public.bunker_state(
    event_id, status, started_at, duration_seconds, phase, phase_started_at,
    unlocked_at, run_nonce, updated_at
  )
  values (
    p_event_id, 'active', v_started_at, p_duration_seconds, 'emergency', v_started_at,
    null, v_run_nonce, now()
  )
