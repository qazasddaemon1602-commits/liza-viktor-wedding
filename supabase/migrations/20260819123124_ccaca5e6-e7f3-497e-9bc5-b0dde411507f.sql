create or replace function public.get_guest_bunker_state(
  p_event_slug text,
  p_device_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event_id uuid;
  v_guest_id uuid;
  v_carriage_id uuid;
  v_carriage_number integer;
  v_state public.bunker_state%rowtype;
  v_profile public.bunker_guest_profiles%rowtype;
  v_progress public.bunker_team_progress%rowtype;
  v_template public.bunker_mission_templates%rowtype;
  v_now timestamptz := clock_timestamp();
  v_remaining integer := 0;
  v_rank integer := 0;
  v_stage text;
  v_dossier jsonb;
  v_team jsonb := null;
begin
  select e.id into v_event_id
  from public.events e
  where e.slug = public._normalize_spaces(p_event_slug);

  if v_event_id is null then
    return jsonb_build_object('status', 'not_found', 'serverNow', v_now);
  end if;

  v_guest_id := public._bunker_guest_id(p_event_slug, p_device_key);
  if v_guest_id is null then
    return jsonb_build_object('status', 'guest_not_found', 'serverNow', v_now);
  end if;

  select g.carriage_id, c.number
  into v_carriage_id, v_carriage_number
  from public.guests g
  join public.carriages c on c.id = g.carriage_id
  where g.id = v_guest_id and g.event_id = v_event_id;

  select b.* into v_state
  from public.bunker_state b
  where b.event_id = v_event_id;

  if v_state.event_id is null or v_state.status <> 'active' or v_state.started_at is null then
    return jsonb_build_object('status', 'idle', 'serverNow', v_now);
  end if;

  v_remaining := greatest(
    0,
    v_state.duration_seconds - floor(extract(epoch from (v_now - v_state.started_at)))::integer
  );

  v_rank := case v_state.phase
    when 'emergency' then 0
    when 'dossier_1' then 1
    when 'dossier_2' then 2
    when 'mission_a' then 3
    when 'mission_b' then 4
    when 'final' then 5
    when 'completed' then 6
    else 0
  end;

  if v_rank >= 1 and v_state.run_nonce is not null then
    perform public._ensure_bunker_guest_profile(v_event_id, v_state.run_nonce, v_guest_id);
    select p.* into v_profile
    from public.bunker_guest_profiles p
    where p.run_nonce = v_state.run_nonce and p.guest_id = v_guest_id;
  end if;

  v_dossier := case when v_rank >= 1 then jsonb_build_object(
    'profession', v_profile.profession,
    'profile', v_profile.profile,
    'health', case when v_rank >= 2 then v_profile.health else null end,
    'hobby', case when v_rank >= 2 then v_profile.hobby else null end,
    'baggage', case when v_rank >= 2 then v_profile.baggage else null end,
    'hiddenFact', case when v_rank >= 2 then v_profile.hidden_fact else null end
  ) else null end;

  if v_state.phase in ('mission_a', 'mission_b') and v_state.run_nonce is not null then
    v_stage := v_state.phase;
    select p.* into v_progress
    from public.bunker_team_progress p
    where p.run_nonce = v_state.run_nonce
      and p.carriage_id = v_carriage_id
      and p.stage = v_stage;

    if v_progress.id is not null then
      select t.* into v_template
      from public.bunker_mission_templates t
      where t.id = v_progress.mission_template_id;

      v_team := jsonb_build_object(
        'carriageNumber', v_carriage_number,
        'stage', v_stage,
        'mission', jsonb_build_object(
          'title', v_template.title,
          'prompt', v_template.prompt,
          'options', v_template.options
        ),
        'completed', v_progress.completed_at is not null,
        'attemptCount', v_progress.attempt_count,
        'fragment', case
          when v_progress.stage = 'mission_b' and v_progress.completed_at is not null
          then v_progress.reward_fragment
          else null
        end
      );
    end if;
  elsif v_state.run_nonce is not null and v_rank >= 5 then
    select p.* into v_progress
    from public.bunker_team_progress p
    where p.run_nonce = v_state.run_nonce
      and p.carriage_id = v_carriage_id
      and p.stage = 'mission_b';

    v_team := jsonb_build_object(
      'carriageNumber', v_carriage_number,
      'completed', v_progress.completed_at is not null,
      'fragment', case when v_progress.completed_at is not null then v_progress.reward_fragment else null end
    );
  end if;

  return jsonb_build_object(
    'status', 'active',
    'phase', v_state.phase,
    'phaseStartedAt', v_state.phase_started_at,
    'startedAt', v_state.started_at,
    'durationSeconds', v_state.duration_seconds,
    'remainingSeconds', v_remaining,
    'serverNow', v_now,
    'dossier', v_dossier,
    'team', v_team,
    'final', jsonb_build_object('unlocked', v_state.unlocked_at is not null)
  );
end;
$$;

create or replace function public.submit_guest_bunker_mission(
  p_event_slug text,
  p_device_key text,
  p_stage text,
  p_answer text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event_id uuid;
  v_guest_id uuid;
  v_carriage_id uuid;
  v_state public.bunker_state%rowtype;
  v_progress public.bunker_team_progress%rowtype;
  v_template public.bunker_mission_templates%rowtype;
  v_answer text := upper(public._normalize_spaces(p_answer));
  v_correct boolean := false;
begin
  select e.id into v_event_id
  from public.events e
  where e.slug = public._normalize_spaces(p_event_slug);

  v_guest_id := public._bunker_guest_id(p_event_slug, p_device_key);
  if v_event_id is null or v_guest_id is null then
    raise exception 'guest access required' using errcode = '42501';
  end if;

  if p_stage not in ('mission_a', 'mission_b') then
    raise exception 'invalid bunker mission stage' using errcode = '22023';
  end if;

  select b.* into v_state
  from public.bunker_state b
  where b.event_id = v_event_id;

  if v_state.event_id is null or v_state.status <> 'active' or v_state.phase <> p_stage then
    raise exception 'bunker mission is not active' using errcode = '55000';
  end if;

  select g.carriage_id into v_carriage_id
  from public.guests g
  where g.id = v_guest_id and g.event_id = v_event_id;

  select p.* into v_progress
  from public.bunker_team_progress p
  where p.run_nonce = v_state.run_nonce
    and p.carriage_id = v_carriage_id
    and p.stage = p_stage
  for update;

  if v_progress.id is null then
    raise exception 'bunker team mission not initialized' using errcode = '55000';
  end if;

  if v_progress.completed_at is not null then
    return jsonb_build_object(
      'status', 'completed',
      'stage', p_stage,
      'fragment', case when p_stage = 'mission_b' then v_progress.reward_fragment else null end
    );
  end if;

  select t.* into v_template
  from public.bunker_mission_templates t
  where t.id = v_progress.mission_template_id;

  v_correct := v_answer = upper(public._normalize_spaces(v_template.correct_answer));

  update public.bunker_team_progress
  set attempt_count = attempt_count + 1,
      completed_at = case when v_correct then clock_timestamp() else completed_at end,
      completed_by_guest_id = case when v_correct then v_guest_id else completed_by_guest_id end,
      updated_at = now()
  where id = v_progress.id
  returning * into v_progress;

  if not v_correct then
    return jsonb_build_object(
      'status', 'incorrect',
      'stage', p_stage,
      'attemptCount', v_progress.attempt_count
    );
  end if;

  return jsonb_build_object(
    'status', 'completed',
    'stage', p_stage,
    'attemptCount', v_progress.attempt_count,
    'successCopy', v_template.success_copy,
    'fragment', case when p_stage = 'mission_b' then v_progress.reward_fragment else null end
  );
end;
$$;

create or replace function public.submit_guest_bunker_final_code(
  p_event_slug text,
  p_device_key text,
  p_code text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_event_id uuid;
  v_guest_id uuid;
  v_state public.bunker_state%rowtype;
  v_expected text;
  v_submitted text := regexp_replace(coalesce(p_code, ''), '[^0-9]', '', 'g');
  v_completed_count integer := 0;
  v_correct boolean := false;
begin
  select e.id into v_event_id
  from public.events e
  where e.slug = public._normalize_spaces(p_event_slug);

  v_guest_id := public._bunker_guest_id(p_event_slug, p_device_key);
