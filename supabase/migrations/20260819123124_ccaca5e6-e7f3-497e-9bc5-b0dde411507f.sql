create or replace function public.owner_advance_bunker_phase(
  p_event_id uuid,
  p_phase text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_state public.bunker_state%rowtype;
  v_expected text;
  v_required integer := 0;
  v_completed integer := 0;
begin
  perform public._require_bunker_owner(p_event_id);

  select b.* into v_state
  from public.bunker_state b
  where b.event_id = p_event_id
  for update;

  if v_state.event_id is null or v_state.status <> 'active' then
    raise exception 'bunker is not active' using errcode = '55000';
  end if;

  v_expected := case v_state.phase
    when 'dossier_1' then 'dossier_2'
    when 'dossier_2' then 'mission_a'
    when 'mission_a' then 'mission_b'
    when 'mission_b' then 'final'
    when 'final' then 'completed'
    else null
  end;

  if v_expected is null or p_phase <> v_expected then
    raise exception 'invalid bunker phase transition: % -> %', v_state.phase, p_phase using errcode = '22023';
  end if;

  if v_state.phase in ('mission_a', 'mission_b') then
    select count(*)::integer into v_required
    from public.carriages c
    where c.event_id = p_event_id and c.enabled;

    select count(*)::integer into v_completed
    from public.bunker_team_progress p
    where p.event_id = p_event_id
      and p.run_nonce = v_state.run_nonce
      and p.stage = v_state.phase
      and p.completed_at is not null;

    if v_completed < v_required then
      raise exception 'all carriages must complete current bunker mission first' using errcode = '55000';
    end if;
  end if;

  if v_state.phase = 'final' and v_state.unlocked_at is null then
    raise exception 'bunker must be unlocked before completion' using errcode = '55000';
  end if;

  update public.bunker_state
  set phase = p_phase,
      phase_started_at = clock_timestamp(),
      updated_at = now()
  where event_id = p_event_id;

  insert into public.owner_action_log(event_id, owner_user_id, action, payload)
  values (
    p_event_id,
    auth.uid(),
    'bunker_phase_advanced',
    jsonb_build_object('from', v_state.phase, 'to', p_phase)
  );

  return public.owner_get_bunker_quest(p_event_id);
end;
$$;

