create table public.events (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  wedding_date date not null default date '2026-08-29',
  event_date date not null default date '2026-08-30',
  expected_guest_count integer not null default 40 check (expected_guest_count > 0),
  registration_open boolean not null default true,
  composition_locked boolean not null default false,
  next_ticket_sequence bigint not null default 1 check (next_ticket_sequence > 0),
  owner_user_id uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table public.event_state (
  event_id uuid primary key references public.events(id) on delete cascade,
  current_module text not null default 'idle',
  screen_mode text not null default 'idle',
  screen_payload_id uuid,
  screen_payload jsonb,
  screen_pinned boolean not null default false,
  updated_at timestamptz not null default now()
);

create table public.carriages (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  number integer not null check (number > 0),
  label text not null,
  accent_hex text not null check (accent_hex ~ '^#[0-9A-Fa-f]{6}$'),
  visual_mark text not null,
  sort_order integer not null,
  enabled boolean not null default true,
  unique (event_id, number),
  unique (event_id, sort_order)
);

create table public.guests (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  first_name text not null check (length(btrim(first_name)) > 0),
  last_name text not null check (length(btrim(last_name)) > 0),
  affiliation_type text not null check (
    affiliation_type in ('liza', 'viktor', 'common', 'family', 'colleagues', 'other')
  ),
  affiliation_detail text,
  carriage_id uuid not null references public.carriages(id) on delete restrict,
  ticket_sequence bigint not null check (ticket_sequence > 0),
  ticket_number text not null,
  registered_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique (event_id, ticket_sequence),
  unique (event_id, ticket_number)
);

create table public.guest_device_bindings (
  event_id uuid not null references public.events(id) on delete cascade,
  guest_id uuid not null references public.guests(id) on delete cascade,
  device_key_hash text not null,
  created_at timestamptz not null default now(),
  primary key (event_id, device_key_hash),
  unique (event_id, guest_id)
);

create table public.guest_recovery_codes (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  guest_id uuid not null references public.guests(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  consumed_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.owner_action_log (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.events(id) on delete cascade,
  owner_user_id uuid not null references auth.users(id) on delete restrict,
  action text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.carriage_calls (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  message text not null check (length(btrim(message)) > 0),
  active boolean not null default true,
  show_on_screen boolean not null default false,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  cleared_at timestamptz
);

create table public.carriage_call_targets (
  call_id uuid not null references public.carriage_calls(id) on delete cascade,
  carriage_id uuid not null references public.carriages(id) on delete cascade,
  primary key (call_id, carriage_id)
);

create index guests_event_carriage_idx on public.guests(event_id, carriage_id);
create index guests_event_affiliation_idx on public.guests(event_id, affiliation_type);
create index guests_event_name_idx on public.guests(event_id, lower(first_name), lower(last_name));
create index carriage_calls_event_active_idx on public.carriage_calls(event_id, active) where active;

